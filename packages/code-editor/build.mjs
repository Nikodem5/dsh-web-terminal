// Builds lib/client.js: one classic IIFE script wrapped for window.__ModuleLoader__.load.
// Monaco (lite: editor worker + Monarch highlighting, no TypeScript language service) is bundled in; its
// worker and CSS (codicon font inlined) are built first and embedded as strings through virtual modules.
// Monaco itself is only EXECUTED on first use (the adapter module is imported dynamically).
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, 'src')
const out = join(here, 'lib', 'client.js')
const EXPORTS = '__dsh_ce_exports__'

// Host helpers shared with the other plugins are copied into lib/shared by the host half's script (if present).
const copyShared = join(here, 'scripts', 'copy-shared-host.mjs')
if (existsSync(copyShared)) await import(pathToFileURL(copyShared).href)
else console.log('(scripts/copy-shared-host.mjs not present: skipping lib/shared copy)')

const monacoDir = dirname(createRequire(import.meta.url).resolve('monaco-editor/package.json'))
const monacoVersion = JSON.parse(readFileSync(join(monacoDir, 'package.json'), 'utf8')).version

const editorWorker = (await build({
  entryPoints: [join(monacoDir, 'esm', 'vs/editor/editor.worker.js')], bundle: true, format: 'iife', platform: 'browser',
  target: ['es2020'], minify: true, write: false, legalComments: 'none', logLevel: 'error',
})).outputFiles[0].text

// All CSS Monaco's ESM build imports, bundled once with the codicon font inlined as a data: URL.
// The css-only plugin replaces every JS module by just its relative imports (CSS survives).
const cssRes = await build({
  stdin: { contents: "import 'monaco-editor/esm/vs/editor/editor.all.js'\n", resolveDir: here, loader: 'js' },
  bundle: true, write: false, outdir: 'cssout', minify: true, logLevel: 'error', format: 'esm',
  platform: 'browser', target: ['es2020'], loader: { '.ttf': 'dataurl' },
  plugins: [{
    name: 'css-only',
    setup(b) {
      b.onLoad({ filter: /\.js$/ }, (a) => {
        const text = readFileSync(a.path, 'utf8')
        const specs = [...text.matchAll(/^\s*import\s+(?:[^'"\n]*from\s+)?['"]([^'"]+)['"]/gm)].map((m) => m[1])
        const dyn = [...text.matchAll(/import\(\s*['"]([^'"]+)['"]\s*\)/g)].map((m) => m[1])
        const all = [...new Set([...specs, ...dyn])].filter((s) => s.startsWith('.') || s.startsWith('monaco-editor'))
        return { contents: all.map((p) => `import ${JSON.stringify(p)}`).join('\n'), resolveDir: dirname(a.path), loader: 'js' }
      })
    },
  }],
})
const cssText = cssRes.outputFiles.filter((f) => f.path.endsWith('.css')).map((f) => f.text).join('\n')
if (!cssText.includes('codicon') || !cssText.includes('data:font')) console.warn('WARNING: codicon font not inlined in CSS')

const virtual = {
  name: 'virtual',
  setup(b) {
    b.onResolve({ filter: /^ce-(worker|css):/ }, (a) => ({ path: a.path, namespace: 'ce' }))
    b.onLoad({ filter: /.*/, namespace: 'ce' }, (a) => ({
      contents: `export default ${JSON.stringify(a.path === 'ce-worker:editor' ? editorWorker : cssText)}`, loader: 'js',
    }))
  },
}

const result = await build({
  entryPoints: [join(src, 'client', 'index.ts')], bundle: true, format: 'iife', globalName: EXPORTS,
  platform: 'browser', target: ['es2020'], minify: true, legalComments: 'none', logLevel: 'warning',
  outfile: out, write: false, jsx: 'automatic',
  loader: { '.css': 'empty' }, // Monaco CSS is inlined once as a string (ce-css:all)
  define: { __MONACO_VERSION__: JSON.stringify(monacoVersion) },
  alias: { react: join(src, 'shims', 'react.cts'), 'react/jsx-runtime': join(src, 'shims', 'jsx-runtime.cts') },
  plugins: [virtual], absWorkingDir: here,
  banner: { js: '// Generated by build.mjs from src/ - edit the sources, then rebuild.\n' + readFileSync(join(src, 'client-prelude.js'), 'utf8').trimEnd() },
  footer: { js: readFileSync(join(src, 'client-postlude.js'), 'utf8').trimEnd() },
})
const text = result.outputFiles[0].text
if (!text.includes(EXPORTS) || !/var module = \{ exports: \{\} \}/.test(text) || !/return module\.exports;/.test(text) || !text.includes('globalThis.__ce_require__ = require')) {
  console.error('bundle wrapper check failed'); process.exit(1)
}
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, text)
const bytes = Buffer.byteLength(text)
console.log(`monaco ${monacoVersion}: editor worker ${editorWorker.length} B, css ${cssText.length} B`)
console.log(`wrote ${out} (${bytes} bytes, ${(bytes / 1048576).toFixed(2)} MiB)`)

// Builds the client half into the single classic script DSH serves verbatim:
// lib/client.js. Run with `npm run build` (or `node build.mjs`) inside this
// package.
//
// The real TypeScript/TSX sources are the esbuild entry (so JSX is transformed
// by esbuild rather than hand-rolled); the `window.__ModuleLoader__.load(...)`
// wrapper is added around the emitted IIFE as banner/footer text. React is
// routed to the loader's shared instance through the shim modules, while xterm
// is bundled in.

import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, 'src')
const out = join(here, 'lib', 'client.js')

// Host helpers shared with the other plugins (packages/shared/host) must live inside the
// installed package, which cannot reach packages/shared: copy them into lib/shared/ (gitignored).
const sharedHost = join(here, '..', 'shared', 'host')
const sharedOut = join(here, 'lib', 'shared')
rmSync(sharedOut, { recursive: true, force: true })
mkdirSync(sharedOut, { recursive: true })
cpSync(sharedHost, sharedOut, { recursive: true })

/** The variable name esbuild gives the bundled entry's exports in IIFE output. */
const BUNDLED_EXPORTS = '__dsh_wt_exports__'

const result = await build({
  entryPoints: [join(src, 'client', 'index.ts')],
  bundle: true,
  format: 'iife',
  globalName: BUNDLED_EXPORTS,
  platform: 'browser',
  target: ['es2020'],
  minify: false,
  legalComments: 'none',
  logLevel: 'info',
  outfile: out,
  jsx: 'automatic',
  alias: {
    react: join(src, 'shims', 'react.cts'),
    'react/jsx-runtime': join(src, 'shims', 'jsx-runtime.cts'),
  },
  // Deterministic, reviewable output: no source maps and no absolute paths.
  sourcemap: false,
  absWorkingDir: here,
  banner: {
    js: [
      '// Generated by build.mjs from src/ — edit the sources, then rebuild.',
      readFileSync(join(src, 'client-prelude.js'), 'utf8').trimEnd(),
    ].join('\n'),
  },
  footer: { js: readFileSync(join(src, 'client-postlude.js'), 'utf8').trimEnd() },
})

if (result.errors.length > 0) {
  console.error('client bundle failed')
  process.exit(1)
}

const emitted = readFileSync(out, 'utf8')
if (!emitted.includes(BUNDLED_EXPORTS)) {
  console.error(`client bundle is missing the expected exports binding "${BUNDLED_EXPORTS}" — adjust BUNDLED_EXPORTS to match the emitted name`)
  process.exit(1)
}
if (!emitted.includes("globalThis.__wt_require__ = require")) {
  console.error('client bundle is missing the loader prelude — the React shim would have no hook')
  process.exit(1)
}
// The factory body is not a CommonJS scope: `module` only exists because the
// prelude declares it. Losing that line fails inside the browser as
// "module is not defined", which no amount of host-side testing would reveal.
if (!/var module = \{ exports: \{\} \}/.test(emitted)) {
  console.error('client bundle does not declare `module` inside the loader factory — the postlude would throw "module is not defined" in the browser')
  process.exit(1)
}
if (!/return module\.exports;/.test(emitted)) {
  console.error('client bundle does not return module.exports from the factory — the loader would materialize the plugin as undefined')
  process.exit(1)
}

writeFileSync(out, emitted)
console.log(`wrote ${out} (${emitted.length} bytes)`)
